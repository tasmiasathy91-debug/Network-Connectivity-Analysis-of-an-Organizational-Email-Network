"""Question 1

Using networkx, load up the directed multigraph from assets/email_network.txt. Make sure the node names are strings.

This function should return a directed multigraph networkx graph.
"""

import networkx as nx

def answer_one():
    return nx.read_edgelist(
        "assets/email_network.txt",
        create_using=nx.MultiDiGraph(),
        nodetype=str,
        data=[("time", int)]
    )

"""Question 2

How many employees are represented in the network?

How many sender->recipient pairs of employees are there in the network such that sender sent at least one email to recipient?

This function should return a tuple with two integers (#employees, # sender->recipient pairs).
"""

def answer_two():
    G = answer_one()

    num_employees = G.number_of_nodes()
    num_pairs = len(set(G.edges()))

    return (num_employees, num_pairs)

"""Question 3


Part 1. Assume that information in this company can only be exchanged through email.

When an employee sends an email to another employee, a communication channel has been created, allowing the sender to provide information to the reciever, but not viceversa.

Based on the emails sent in the data, is it possible for information to go from every employee to every other employee?

Part 2. Now assume that a communication channel established by an email allows information to be exchanged both ways.

Based on the emails sent in the data, is it possible for information to go from every employee to every other employee?

This function should return a tuple of bools (part1, part2).
"""

def answer_three():
    G = answer_one()

    part1 = nx.is_strongly_connected(G)
    part2 = nx.is_weakly_connected(G)

    return (part1, part2)

"""Question 4

How many nodes are in the largest weakly connected component of the graph?

This function should return an int.
"""

def answer_four():
    G = answer_one()
    largest_component = max(nx.weakly_connected_components(G), key=len)
    return len(largest_component)

"""Question 5

How many nodes are in the largest strongly connected component?

This function should return an int
"""

def answer_five():
    G = answer_one()
    largest_component = max(nx.strongly_connected_components(G), key=len)
    return len(largest_component)

"""Question 6

Using the NetworkX functions strongly_connected_components and subgraph, find the subgraph of nodes in the largest strongly connected component. Call this graph G_sc.

This function should return a networkx MultiDiGraph named G_sc.
"""

def answer_six():
    G = answer_one()
    largest_component = max(nx.strongly_connected_components(G), key=len)
    G_sc = G.subgraph(largest_component).copy()
    return G_sc

"""Question 7

What is the average distance between nodes in G_sc?

This function should return a float.
"""

def answer_seven():
    G_sc = answer_six()
    return float(nx.average_shortest_path_length(G_sc))

"""Question 8

What is the largest possible distance between two employees in G_sc?

This function should return an int.
"""

def answer_eight():
    G_sc = answer_six()
    return int(nx.diameter(G_sc))

"""Question 9

What is the set of nodes in G_sc with eccentricity equal to the diameter?

This function should return a set of the node(s).
"""

def answer_nine():
    G_sc = answer_six()
    return set(nx.periphery(G_sc))

"""Question 10

What is the set of node(s) in G_sc with eccentricity equal to the radius?

This function should return a set of the node(s).
"""

def answer_ten():
    G_sc = answer_six()
    return set(nx.center(G_sc))

"""Question 11

Which node in G_sc has the most shortest paths to other nodes whose distance equal the diameter of G_sc?

For the node with the most such shortest paths, how many of these paths are there?

This function should return a tuple (name of node, number of paths).
"""

def answer_eleven():
    G_sc = answer_six()
    diameter = nx.diameter(G_sc)

    counts = {}
    for node in G_sc:
        distances = nx.single_source_shortest_path_length(G_sc, node)
        counts[node] = sum(d == diameter for d in distances.values())

    best_node = max(counts, key=counts.get)
    return (best_node, counts[best_node])

"""Question 12

 What is the smallest number of nodes it would need to remove from the graph

This function should return an integer.
"""

def answer_twelve():
    G_sc = answer_six()
    source = answer_eleven()[0]

    G = nx.DiGraph(G_sc)
    cut_nodes = nx.minimum_node_cut(G, s=source, t="10")

    return len(cut_nodes)

"""Question 13

Convert the graph G_sc into an undirected graph by removing the direction of the edges of G_sc. Call the new graph G_un.

This function should return a networkx Graph.
"""

def answer_thirteen():
    G_sc = answer_six()
    G_un = nx.Graph(G_sc)
    return G_un

"""Question 14

What is the transitivity and average clustering coefficient of graph G_un?

This function should return a tuple (transitivity, avg clustering).
Note: DO NOT round up your answer.
"""

def answer_fourteen():
    G_un = answer_thirteen()
    return (nx.transitivity(G_un), nx.average_clustering(G_un))